import Testing
import AppKit
import IslandCore
@testable import IslandUI

/// These use a real NSPasteboard (a private, uniquely named one), so the code that reads real pasteboard types
/// is exercised without touching the user's clipboard.
@MainActor
private struct RealPasteboardRig {
    let pasteboard: NSPasteboard
    let history: ClipboardHistory
    let imagesDirectory: URL
    let monitor: PasteboardMonitor

    init() {
        pasteboard = NSPasteboard(name: NSPasteboard.Name("dev.island.tests.\(UUID().uuidString)"))
        let directory = FileManager.default.temporaryDirectory
            .appendingPathComponent("island-ui-tests-\(UUID().uuidString)", isDirectory: true)
        imagesDirectory = directory.appendingPathComponent("images", isDirectory: true)
        history = ClipboardHistory(store: FileStore(url: directory.appendingPathComponent("clip.json"), defaultValue: []))
        monitor = PasteboardMonitor(
            history: history, imagesDirectory: imagesDirectory,
            pasteboard: SystemPasteboard(pasteboard: pasteboard), ocr: { _ in "" })
        monitor.start()
    }

    func copyText(_ text: String, alsoDeclaring extra: [String] = []) {
        pasteboard.clearContents()
        let types = [NSPasteboard.PasteboardType.string] + extra.map { NSPasteboard.PasteboardType($0) }
        pasteboard.declareTypes(types, owner: nil)
        pasteboard.setString(text, forType: .string)
        for type in extra { pasteboard.setData(Data([1]), forType: NSPasteboard.PasteboardType(type)) }
    }
}

@Test @MainActor func aConcealedCopyOnARealPasteboardIsNeverRecorded() {
    let rig = RealPasteboardRig()
    defer { rig.pasteboard.releaseGlobally() }
    rig.copyText("hunter2", alsoDeclaring: ["org.nspasteboard.ConcealedType"])
    rig.monitor.poll()
    #expect(rig.history.entries.isEmpty)
}

@Test @MainActor func transientAndAutoGeneratedCopiesAreSkippedToo() {
    for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
        let rig = RealPasteboardRig()
        defer { rig.pasteboard.releaseGlobally() }
        rig.copyText("one-time code 123456", alsoDeclaring: [marker])
        rig.monitor.poll()
        #expect(rig.history.entries.isEmpty, "\(marker)")
    }
}

@Test @MainActor func ordinaryTextOnARealPasteboardIsRecorded() {
    let rig = RealPasteboardRig()
    defer { rig.pasteboard.releaseGlobally() }
    rig.copyText("meeting at 3")
    rig.monitor.poll()
    #expect(rig.history.entries.map(\.content) == [.text("meeting at 3")])
}

@Test @MainActor func copiedFilesOnARealPasteboardAreRecordedAsFiles() throws {
    let rig = RealPasteboardRig()
    defer { rig.pasteboard.releaseGlobally() }
    let file = FileManager.default.temporaryDirectory.appendingPathComponent("island-\(UUID().uuidString).txt")
    try "x".write(to: file, atomically: true, encoding: .utf8)
    rig.pasteboard.clearContents()
    rig.pasteboard.writeObjects([file as NSURL])
    rig.monitor.poll()

    guard case .files(let urls)? = rig.history.entries.first?.content else {
        Issue.record("expected a files entry")
        return
    }
    #expect(urls.map { $0.resolvingSymlinksInPath().path } == [file.resolvingSymlinksInPath().path])
}

@Test @MainActor func aCopiedImageOnARealPasteboardIsSavedToIslandsFolder() {
    let rig = RealPasteboardRig()
    defer { rig.pasteboard.releaseGlobally() }
    rig.pasteboard.clearContents()
    rig.pasteboard.setData(makePNG(), forType: .png)
    rig.monitor.poll()

    guard case .image(let fileName)? = rig.history.entries.first?.content else {
        Issue.record("expected an image entry")
        return
    }
    #expect(FileManager.default.fileExists(atPath: rig.imagesDirectory.appendingPathComponent(fileName).path))
}

@Test @MainActor func writingTextBackRoundTripsAndReportsTheNewChangeCount() {
    let rig = RealPasteboardRig()
    defer { rig.pasteboard.releaseGlobally() }
    let system = SystemPasteboard(pasteboard: rig.pasteboard)
    let count = system.write(.text("round trip"), imagesDirectory: rig.imagesDirectory)
    #expect(count == rig.pasteboard.changeCount)
    #expect(system.snapshot().string == "round trip")
}

@Test @MainActor func writingFilesBackRoundTrips() throws {
    let rig = RealPasteboardRig()
    defer { rig.pasteboard.releaseGlobally() }
    let file = FileManager.default.temporaryDirectory.appendingPathComponent("island-\(UUID().uuidString).txt")
    try "x".write(to: file, atomically: true, encoding: .utf8)
    let system = SystemPasteboard(pasteboard: rig.pasteboard)
    _ = system.write(.files([file]), imagesDirectory: rig.imagesDirectory)
    #expect(system.snapshot().fileURLs.map { $0.resolvingSymlinksInPath().path } == [file.resolvingSymlinksInPath().path])
}
